bold_w = {
    '1': 3.16015625, '2': 4.76171875, '3': 4.83984375, '4': 4.87890625, '5': 4.83984375,
    '6': 4.87890625, '7': 4.3203125, '8': 4.9609375, '9': 4.87890625, '0': 5.4375,
    '.': 1.83984375, ',': 1.83984375, ' ': 1.83984375, '+': 4.83984375, '-': 3.16015625
}

def get_bold_w(s):
    return sum(bold_w.get(c, 4.8) for c in s)

v1 = "2.615.994,81"
v2 = "+ 7.157.000,00"
v3 = "- 4.042.325,00"
v4 = "5.730.669,81"

for label, val in [("Saldo Awal", v1), ("Dana Masuk", v2), ("Dana Keluar", v3), ("Saldo Akhir", v4)]:
    w = get_bold_w(val)
    x0 = 567.00 - w
    print(f"{label:<15}: '{val}' | width={w:.2f} | x0={x0:.2f}")
